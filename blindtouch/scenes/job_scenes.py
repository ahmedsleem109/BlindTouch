"""Scenes for the contact jobs, built from real-dimension props (:mod:`blindtouch.scenes.props`): exact convex
contact pieces, detailed visual meshes on top.

    python -m blindtouch.scenes.job_scenes     # writes blindtouch/scenes/job_<kind>{,_nominal}.xml

kind        job                                         held tool
socket      plug in a charger behind the TV             Europlug
whiteboard  wipe a sloped whiteboard at steady pressure  eraser
cans        which cans are still full?                   (empty hand)

Plant scenes hold the tool as a free body gripped by friction; nominal scenes (what the controller and the
observers believe) hold only its mass at the pads' centre. Fixtures sit on the mocap body ``fixture`` (origin
on the table surface), which a task moves and turns per episode.
"""

from __future__ import annotations

import math
from pathlib import Path


from blindtouch.scenes import props as P
from blindtouch.scenes.build import GEOM, SCENE_DIR, STUDIO, WORLD_COMMON, _lookat, arm_xml

TOOL_OF = {"whiteboard": "eraser", "cans": "empty", "socket": "europlug"}
KINDS = tuple(TOOL_OF)
TABLE = GEOM.table_top
PAD_Z = -0.164          # centre of the finger pads below the hand origin (pads span -171 .. -157 mm)
WHITEBOARD_TILT = math.radians(15)   # nominal slope of the board (per episode +- a few degrees)
WHITEBOARD_Z = 0.07                  # board centre above the table


def grip_angle(kind: str) -> float:
    """Finger hinge angle that closes the pads on the job's tool (opening ~ 2 * 93 mm * sin(angle))."""
    tool = TOOL_OF.get(kind)
    if tool is None or tool == "empty":
        return GEOM.finger_angle
    w = P.TOOLS[tool]().grip_width
    return math.asin(min(w / 2 / 0.093, 0.99))


def _fixture(kind: str):
    """(assets, body xml, info) of the kind's fixture on the mocap body ``fixture``."""
    hx, hy = GEOM.hole_nominal
    if kind == "cans":
        return [], "", {}
    if kind == "socket":
        a, g, info = P.socket_strip()
    elif kind == "whiteboard":
        a, g, info = P.whiteboard()
        q = (math.cos(-WHITEBOARD_TILT / 2), 0, math.sin(-WHITEBOARD_TILT / 2), 0)
        wedge = '<geom class="vis" type="box" size="0.10 0.14 0.03" pos="0.02 0 0.03" material="grey_plastic"/>'
        g = (wedge + f'\n      <body name="board" pos="0 0 {WHITEBOARD_Z:g}" quat="{P._fmt(q)}">\n      '
             + g + '\n      <site name="board_top" pos="0 0 0.004" size="0.003" group="4"/>\n      </body>')
    else:
        raise ValueError(kind)
    body = f'    <body name="fixture" mocap="true" pos="{hx:.6g} {hy:.6g} {TABLE:.6g}">\n      {g}\n    </body>\n'
    return a, body, info


def tool_free_body(tool: str) -> tuple[list, str]:
    if tool == "empty":
        return [], ""
    t = P.TOOLS[tool]()
    return t.assets, (f'    <body name="peg" pos="0 0 {GEOM.mount_z + PAD_Z:.6g}">\n'
                      f'      <freejoint name="peg_free"/>{t.body("peg")}\n    </body>\n')


def job_scene_xml(kind: str, nominal: bool = False) -> str:
    tool = TOOL_OF[kind]
    hx, hy = GEOM.hole_nominal
    focus = (hx, hy, GEOM.plate_top + 0.02)
    cameras = "\n    ".join([
        _lookat((hx + 0.30, hy - 0.26, GEOM.plate_top + 0.24), focus, 42, "front"),
        _lookat((hx + 1.05, hy - 1.00, GEOM.plate_top + 0.62), (0.15, -0.12, GEOM.plate_top + 0.15), 40, "overview"),
    ])
    tx, ty = GEOM.table_center
    thx, thy = GEOM.table_half
    world = WORLD_COMMON.format(ped_z=GEOM.mount_z / 2 - 0.03, tx=tx, ty=ty, tz=TABLE - 0.02, thx=thx, thy=thy, cameras=cameras)
    a, extra = _fixture(kind)[:2]   # the believed world has the furniture too (it never collides: contacts off)
    assets = list(a)
    if not nominal:
        if kind == "cans":
            assets.append(P.can_mesh())
            extra += P.cans_bodies(nominal)
        if kind == "socket":
            extra += "    " + P.tv_occluder() + "\n"
        a, body = tool_free_body(tool)
        assets += a
        extra += body
    arm = _arm_file(tool, nominal)
    asset_xml = "  <asset>\n" + P.MATERIALS + "\n".join(assets) + "\n  </asset>\n"
    return f"""<!-- Generated by blindtouch/scenes/job_scenes.py -- edit that file (and props.py), not this one. -->
<mujoco model="blind_touch_job_{kind}{'_nominal' if nominal else ''}">
  <include file="{arm}"/>
  <option timestep="0.001" integrator="implicitfast" cone="elliptic" impratio="20" noslip_iterations="5"/>
  <default>
    <default class="fx">
      <geom type="box" material="grey_plastic" group="3" contype="1" conaffinity="2" condim="3" friction="0.4 0.005 0.0001" solref="0.004 1" solimp="0.95 0.99 0.001"/>
    </default>
    <default class="peg">
      <geom contype="3" conaffinity="3" condim="3" solref="0.004 1"/>
    </default>
    <default class="obj">
      <geom contype="3" conaffinity="3" condim="4" friction="0.6 0.005 0.0001" solref="0.004 1"/>
    </default>
    <default class="vis">
      <geom contype="0" conaffinity="0" group="2"/>
    </default>
  </default>
{STUDIO}{asset_xml}
  <worldbody>
{world}
{extra}
  </worldbody>
</mujoco>
"""


def _arm_file(tool: str, nominal: bool) -> str:
    if nominal:
        return "openarm_right_rigid_empty.xml" if tool == "empty" else f"openarm_right_rigid_job_{tool}.xml"
    return "openarm_right_empty.xml" if tool == "empty" else "openarm_right_job.xml"


# Finger pads in the job scenes: condim 6 adds rolling friction (0.01 m, the template's third friction value) -- the
# pad's contact patch resisting a held tool rocking about the line where the pads touch it. Without it a Europlug
# rocked +-2 deg in the fingers while turning (contacts all on one horizontal line). Job scenes only: the peg-in-hole
# scene (blindtouch.scenes.build) keeps the template as it was.
def _job_pads(xml: str) -> str:
    old = 'condim="4" solref="0.004 1" friction="1 0.02 0.01"'
    assert xml.count(old) == 1, "fingertip default changed in the template"
    return xml.replace(old, 'condim="6" solref="0.004 1" friction="1 0.02 0.01"')


def _nominal_tool_body(tool: str) -> str:
    t = P.TOOLS[tool]()
    return (f'<inertial pos="0 0 0" mass="{t.mass:g}" diaginertia="{P._fmt(t.inertia)}" />'
            f'<site name="peg_tip" pos="0 0 {t.tip_z:.6g}" size="0.003" rgba="0 1 0 1" group="4" />')


def build_jobs(kinds=KINDS) -> list[Path]:
    (SCENE_DIR / "openarm_right_empty.xml").write_text(_job_pads(arm_xml(GEOM, grasp=True, tool="empty")), encoding="utf-8")
    (SCENE_DIR / "openarm_right_job.xml").write_text(_job_pads(arm_xml(GEOM, grasp=True)), encoding="utf-8")
    (SCENE_DIR / "openarm_right_rigid_empty.xml").write_text(arm_xml(GEOM, grasp=False, tool="empty"), encoding="utf-8")
    for tool in P.TOOLS:
        ang = math.asin(min(P.TOOLS[tool]().grip_width / 2 / 0.093, 0.99))
        (SCENE_DIR / f"openarm_right_rigid_job_{tool}.xml").write_text(
            arm_xml(GEOM, grasp=False, tool=tool, tool_body=_nominal_tool_body(tool), finger_angle=ang, tool_z=PAD_Z), encoding="utf-8")
    paths = []
    for kind in kinds:
        for nominal in (False, True):
            p = SCENE_DIR / f"job_{kind}{'_nominal' if nominal else ''}.xml"
            p.write_text(job_scene_xml(kind, nominal), encoding="utf-8")
            paths.append(p)
    return paths


def job_scene_path(kind: str, nominal: bool = False) -> Path:
    p = SCENE_DIR / f"job_{kind}{'_nominal' if nominal else ''}.xml"
    srcs = [Path(__file__), SCENE_DIR / "build.py", SCENE_DIR / "props.py", SCENE_DIR / "openarm_right.template.xml"]
    if not p.exists() or p.stat().st_mtime < max(s.stat().st_mtime for s in srcs):
        build_jobs()
    return p


if __name__ == "__main__":
    for p in build_jobs():
        print("wrote", p)
